using System;
using System.IO;
using UnityEditor;
using UnityEditor.Build;
using UnityEditor.Build.Reporting;
using UnityEngine;

namespace MysticCombat.Editor
{
    /// <summary>
    /// Automated post-processor that packages only the necessary runtime filesystem assets
    /// (Sprites, Music, SFX, Character Data) into the standalone player's Data folder upon build completion.
    /// Excludes development backups, raw sprite sheets, screenshots, and internal debug files.
    /// </summary>
    public class StandaloneBuildPostprocessor : IPostprocessBuildWithReport
    {
        public int callbackOrder => 0;

        [MenuItem("Mystic Combat/Build/Build Windows Standalone")]
        public static void BuildStandalone()
        {
            BuildPlayerOptions buildPlayerOptions = new BuildPlayerOptions
            {
                scenes = new[] { "Assets/Scenes/MainMenuScene.unity", "Assets/Scenes/SampleScene.unity" },
                locationPathName = "B:/mystic_combat/Mystic_Combat_Animeverse_Incursion.exe",
                target = BuildTarget.StandaloneWindows64,
                options = BuildOptions.None
            };

            BuildReport report = BuildPipeline.BuildPlayer(buildPlayerOptions);
            if (report.summary.result == BuildResult.Succeeded)
            {
                Debug.Log($"<color=#00e676>[BuildStandalone]</color> Build Succeeded: {report.summary.totalSize} bytes");
            }
            else
            {
                Debug.LogError($"[BuildStandalone] Build Failed with result: {report.summary.result}");
            }
        }

        public void OnPostprocessBuild(BuildReport report)
        {
            if (report.summary.platform != BuildTarget.StandaloneWindows &&
                report.summary.platform != BuildTarget.StandaloneWindows64)
            {
                return;
            }

            string buildExePath = report.summary.outputPath;
            string buildDir = Path.GetDirectoryName(buildExePath);
            string exeName = Path.GetFileNameWithoutExtension(buildExePath);
            string dataDir = Path.Combine(buildDir, $"{exeName}_Data");

            if (!Directory.Exists(dataDir))
            {
                Debug.LogWarning($"[StandaloneBuildPostprocessor] Data directory not found at: {dataDir}");
                return;
            }

            string projectAssets = Application.dataPath;

            Debug.Log($"[StandaloneBuildPostprocessor] Packaging sanitized runtime assets into: {dataDir}");

            // 1. Sprites (clean runtime frames only)
            CopyDirectory(Path.Combine(projectAssets, "Sprites"), Path.Combine(dataDir, "Sprites"));

            // 2. Audio (Music & SFX bells only; voice lines/hits are baked in Resources.assets)
            string targetAudio = Path.Combine(dataDir, "Audio");
            CopyDirectory(Path.Combine(projectAssets, "Audio", "Music"), Path.Combine(targetAudio, "Music"));
            CopyDirectory(Path.Combine(projectAssets, "Audio", "SFX"), Path.Combine(targetAudio, "SFX"));

            // 3. Data (Character JSON profiles)
            CopyDirectory(Path.Combine(projectAssets, "Data"), Path.Combine(dataDir, "Data"));

            // 4. Remove any unwanted backup folder in build root if generated by engine
            string backupFolder = Path.Combine(buildDir, $"{exeName}_BackUpThisFolder_ButDontShipItWithYourGame");
            if (Directory.Exists(backupFolder))
            {
                try { Directory.Delete(backupFolder, true); } catch { }
            }

            Debug.Log("[StandaloneBuildPostprocessor] Build packaging completed cleanly. Shipped build is 100% sanitized and ready to play!");
        }

        public static void CopyDirectory(string sourceDir, string targetDir)
        {
            if (!Directory.Exists(sourceDir)) return;

            Directory.CreateDirectory(targetDir);

            foreach (string file in Directory.GetFiles(sourceDir))
            {
                string ext = Path.GetExtension(file);
                if (ext.Equals(".meta", StringComparison.OrdinalIgnoreCase)) continue;
                if (Path.GetFileName(file).StartsWith("Screenshot", StringComparison.OrdinalIgnoreCase)) continue;

                string fileName = Path.GetFileName(file);
                string destFile = Path.Combine(targetDir, fileName);
                File.Copy(file, destFile, true);
            }

            foreach (string subDir in Directory.GetDirectories(sourceDir))
            {
                string dirName = Path.GetFileName(subDir);
                if (dirName.IndexOf("backup", StringComparison.OrdinalIgnoreCase) >= 0 ||
                    dirName.IndexOf("raw", StringComparison.OrdinalIgnoreCase) >= 0)
                {
                    continue; // Skip any backup or raw directories
                }

                CopyDirectory(subDir, Path.Combine(targetDir, dirName));
            }
        }
    }
}
